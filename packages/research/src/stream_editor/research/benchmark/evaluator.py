"""Semantic evaluation provider for editorial benchmark analysis."""

from typing import Any, Optional
from pydantic import BaseModel, Field
import os
import json

from stream_editor.models.antigravity_client import AntigravityClient


class SegmentSemanticEvaluation(BaseModel):
    is_valid_alternative: bool = Field(
        ...,
        description="True if this segment is high quality editorial content even though human omitted it",
    )
    boundary_naturalness: str = Field(
        default="natural",
        description="One of: 'natural', 'mid_sentence', 'abrupt'",
    )
    narrative_coherence: str = Field(
        default="self_contained",
        description="One of: 'self_contained', 'missing_setup', 'missing_payoff', 'unclear'",
    )
    humor_or_action_rating: float = Field(
        default=0.5,
        description="Score between 0.0 (dull/boring) and 1.0 (peak entertainment)",
    )
    editorial_quality_score: float = Field(
        default=0.7,
        description="Overall editorial rating from 0.0 to 1.0",
    )
    confidence: float = Field(default=1.0)
    reason: str = Field(default="Evaluated against standard editorial criteria")


class EditorialEvaluationProvider:
    """Base protocol for editorial semantic evaluation."""

    async def evaluate_segment(
        self,
        segment_info: dict[str, Any],
        context_transcript: str = "",
    ) -> SegmentSemanticEvaluation:
        raise NotImplementedError


class MockEditorialEvaluationProvider(EditorialEvaluationProvider):
    """Deterministic mock provider for offline and synthetic testing."""

    def __init__(self, default_valid_alternative: bool = True) -> None:
        self.default_valid_alternative = default_valid_alternative

    async def evaluate_segment(
        self,
        segment_info: dict[str, Any],
        context_transcript: str = "",
    ) -> SegmentSemanticEvaluation:
        duration = float(segment_info.get("source_end", 0.0)) - float(segment_info.get("source_start", 0.0))
        reason = segment_info.get("selection_reason", "")

        # If clip is very short (< 0.5s) or marked as dead air
        if duration < 0.5 or "silence" in str(reason).lower():
            return SegmentSemanticEvaluation(
                is_valid_alternative=False,
                boundary_naturalness="abrupt",
                narrative_coherence="unclear",
                humor_or_action_rating=0.1,
                editorial_quality_score=0.2,
                confidence=0.9,
                reason="Segment too short or contains dead air",
            )

        return SegmentSemanticEvaluation(
            is_valid_alternative=self.default_valid_alternative,
            boundary_naturalness="natural",
            narrative_coherence="self_contained",
            humor_or_action_rating=0.8,
            editorial_quality_score=0.85,
            confidence=0.95,
            reason="High energy punchline with coherent setup and clean boundaries",
        )


class AntigravityEditorialEvaluator(EditorialEvaluationProvider):
    """Antigravity / Gemini-based editorial quality evaluator with parity protections."""

    def __init__(
        self,
        model: str = "gemini-3.1-pro-high",
        editor_model: str = "gemini-3.1-pro-high",
    ) -> None:
        self.model = model
        self.editor_model = editor_model
        self.client = AntigravityClient(model=self.model)
        self.mock_fallback = MockEditorialEvaluationProvider()

    async def evaluate_segment(
        self,
        segment_info: dict[str, Any],
        context_transcript: str = "",
    ) -> SegmentSemanticEvaluation:
        if not self.client.is_available:
            return await self.mock_fallback.evaluate_segment(segment_info, context_transcript)

        parity_note = ""
        if self.model == self.editor_model:
            parity_note = (
                "CRITICAL: You are an independent editorial auditor. The candidate segment was generated by an AI "
                "using the same model family. Do NOT give favorable bias. Be ruthlessly critical of boring pauses, "
                "mid-sentence cuts, and repetitive gameplay."
            )

        prompt = f"""
{parity_note}

You are evaluating an editorial cut proposed by an AI video editor that was NOT selected by the human YouTube editor.
Your task is to determine whether this AI-only segment is a VALID ALTERNATIVE (a genuinely entertaining, complete, 
and well-cut moment that the human skipped for time budget) or a FALSE POSITIVE (boring filler, awkward cut, or dead air).

Segment Info:
- Source Time: {segment_info.get('source_start')}s to {segment_info.get('source_end')}s
- Priority: {segment_info.get('priority')}
- Reason given by editor: {segment_info.get('selection_reason')}

Transcript & Context:
{context_transcript or "No transcript text available for this interval."}

Evaluate:
1. is_valid_alternative: True if entertaining and worthy of inclusion, False if filler/mistake.
2. boundary_naturalness: "natural", "mid_sentence", or "abrupt".
3. narrative_coherence: "self_contained", "missing_setup", "missing_payoff", or "unclear".
4. humor_or_action_rating: 0.0 to 1.0.
5. editorial_quality_score: 0.0 to 1.0.
6. reason: Explanation of your editorial evaluation.
"""
        try:
            res: SegmentSemanticEvaluation = await self.client.generate_structured(prompt, SegmentSemanticEvaluation)
            return res
        except Exception:
            return await self.mock_fallback.evaluate_segment(segment_info, context_transcript)
